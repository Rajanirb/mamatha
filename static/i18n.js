window.getTranslation = function(key, lang) {
    return translations[lang]?.[key] ?? translations["en"]?.[key] ?? key;
};

window.setLanguage = function(langCode) {
    console.log("Setting native language to:", langCode);
    localStorage.setItem("siteLang", langCode);
    localStorage.setItem("mamatha_lang", langCode);
    
    document.querySelectorAll('.lang-selector').forEach(sel => {
        sel.value = langCode;
    });

    applyLanguage(langCode);
};

window.applyLanguage = function(langCode) {
    // Standard text content
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        el.textContent = window.getTranslation(key, langCode);
    });

    // Placeholders
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        el.placeholder = window.getTranslation(key, langCode);
    });

    // Titles (tooltips)
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        el.title = window.getTranslation(key, langCode);
    });

    // Aria labels
    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        const key = el.getAttribute('data-i18n-aria-label');
        el.setAttribute('aria-label', window.getTranslation(key, langCode));
    });

    // Alt text
    document.querySelectorAll('[data-i18n-alt]').forEach(el => {
        const key = el.getAttribute('data-i18n-alt');
        el.setAttribute('alt', window.getTranslation(key, langCode));
    });
};

window.applyTranslations = window.applyLanguage; // Backwards compatibility if needed


